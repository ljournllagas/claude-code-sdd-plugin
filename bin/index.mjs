#!/usr/bin/env node
// SDD index: rebuilds the generated catalogue of specs and plans from their frontmatter.
// Derived data: never hand-edited. Exit 0 on success, 1 when the Index cannot be written. Node built-ins only.
import { readFileSync, readdirSync, writeFileSync, renameSync, unlinkSync, mkdirSync } from 'node:fs';
import { resolve, relative, dirname, basename } from 'node:path';
import { loadConfig } from './route.mjs';

export const MARKER = '<!-- Generated by bin/index.mjs from artifact frontmatter. Do not edit; changes are overwritten. -->';
const MAX_BLOCK_LINES = 30;
const TYPES = ['spec', 'plan'];
const REQUIRED = ['type', 'title', 'status'];
const KEY_LINE = /^([a-z_]+):(?: (.*))?$/;

const stripBom = (s) => (s.charCodeAt(0) === 0xfeff ? s.slice(1) : s);
const toSlash = (p) => p.replace(/\\/g, '/');

// Returns { fields } for a valid block, or { reason } (the first failing check of the precedence order).
export function parseFrontmatter(text) {
  const lines = stripBom(String(text)).split(/\r?\n/);
  if (lines[0] !== '---') return { reason: 'no frontmatter' };
  const fields = {};
  let closed = false;
  for (let i = 1; i < MAX_BLOCK_LINES; i++) {
    const line = lines[i];
    if (line === undefined) break;
    if (line === '---') { closed = true; break; }
    if (line.trim() === '' || line.startsWith('#')) continue;
    const m = KEY_LINE.exec(line);
    if (m === null || m[1] in fields) return { reason: `malformed line ${i + 1}` };
    fields[m[1]] = (m[2] ?? '').trim();
  }
  if (!closed) return { reason: 'unterminated frontmatter' };
  for (const k of REQUIRED) if (!fields[k]) return { reason: `missing ${k}` };
  if (!TYPES.includes(fields.type)) return { reason: `unknown type ${fields.type}` };
  return { fields };
}

const byRel = (a, b) => (a.rel < b.rel ? -1 : a.rel > b.rel ? 1 : 0); // UTF-16 code units, not locale order

export function renderIndex({ specs, plans, unindexed }) {
  const entry = (e) => {
    const title = e.title.replace(/[[\]]/g, '\\$&');
    const desc = e.description ? ` — ${e.description}` : '';
    return `- [${title}](${e.rel.replace(/ /g, '%20')}) — ${e.status}${desc}`;
  };
  const section = (heading, lines) => `## ${heading}\n\n${lines.length ? lines.join('\n') : 'None'}`;
  return [
    '# SDD index',
    MARKER,
    section('Specs', [...specs].sort(byRel).map(entry)),
    section('Plans', [...plans].sort(byRel).map(entry)),
    section('Unindexed', [...unindexed].sort(byRel).map((e) => `- ${e.rel} — ${e.reason}`)),
  ].join('\n\n') + '\n';
}

// Lists the *.md files directly inside `dir`. A missing directory is empty; any other failure is empty plus a warning.
function listMarkdown(dir, shown, warn) {
  try {
    return readdirSync(dir, { withFileTypes: true }).filter((d) => d.isFile() && d.name.endsWith('.md')).map((d) => resolve(dir, d.name));
  } catch (e) {
    if (e?.code !== 'ENOENT') warn(`index.mjs: cannot read ${shown}: ${e?.code ?? 'error'}; treating it as empty`);
    return [];
  }
}

export function run(projectDir) {
  const err = [];
  const result = (code, out = '') => ({ code, stdout: out, stderr: err.map((l) => `${l}\n`).join('') });
  try {
    const loaded = loadConfig(projectDir);
    if (!loaded.ok) err.push(loaded.error);
    for (const w of loaded.warnings) err.push(w);
    const { specs: specsPath, plans: plansPath, index: indexPath } = loaded.config.paths;
    const indexAbs = resolve(projectDir, indexPath);
    const indexDir = dirname(indexAbs);
    const dirs = new Map();
    for (const shown of [specsPath, plansPath]) dirs.set(resolve(projectDir, shown), toSlash(shown));

    const specs = [];
    const plans = [];
    const unindexed = [];
    for (const [dir, shown] of dirs) {
      for (const file of listMarkdown(dir, shown, (w) => err.push(w))) {
        if (file === indexAbs) continue;
        const rel = toSlash(relative(indexDir, file));
        let text;
        try { text = readFileSync(file, 'utf8'); } catch { unindexed.push({ rel, reason: 'unreadable' }); continue; }
        const p = parseFrontmatter(text);
        if (p.reason) { unindexed.push({ rel, reason: p.reason }); continue; }
        (p.fields.type === 'spec' ? specs : plans).push({ rel, title: p.fields.title, status: p.fields.status, description: p.fields.description });
      }
    }

    const next = renderIndex({ specs, plans, unindexed });
    const summary = `indexed ${specs.length} specs, ${plans.length} plans, ${unindexed.length} unindexed\n`;
    const shownIndex = toSlash(indexPath);

    let current = null;
    try { current = readFileSync(indexAbs, 'utf8'); } catch (e) {
      if (e?.code !== 'ENOENT') { err.push(`index.mjs: cannot write ${shownIndex}: ${e?.code ?? 'error'}`); return result(1); }
    }
    if (current !== null && current.trim() !== '' && !current.includes(MARKER)) {
      err.push(`index.mjs: ${shownIndex} exists and was not generated by this script; not overwritten`);
      return result(1);
    }
    if (current === next) return result(0, summary);

    const tmp = `${indexAbs}.${process.pid}.tmp`;
    try {
      mkdirSync(indexDir, { recursive: true });
      writeFileSync(tmp, next);
      renameSync(tmp, indexAbs);
    } catch (e) {
      try { unlinkSync(tmp); } catch { /* nothing to remove */ }
      err.push(`index.mjs: cannot write ${shownIndex}: ${e?.code ?? 'error'}`);
      return result(1);
    }
    return result(0, summary);
  } catch (e) {
    err.push(`index.mjs: ${e?.message ?? 'unexpected error'}`);
    return result(1);
  }
}

function main() {
  const r = run(process.cwd());
  process.stdout.write(r.stdout);
  process.stderr.write(r.stderr);
  return r.code;
}

if (basename(process.argv[1] ?? '') === 'index.mjs') process.exitCode = main();
