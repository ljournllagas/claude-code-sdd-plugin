import { test } from 'node:test';
import assert from 'node:assert/strict';
import { mkdtempSync, mkdirSync, writeFileSync, readFileSync, existsSync, readdirSync, statSync, utimesSync, chmodSync } from 'node:fs';
import { tmpdir } from 'node:os';
import { join } from 'node:path';
import { spawnSync } from 'node:child_process';
import { fileURLToPath } from 'node:url';
import * as I from '../bin/index.mjs';

const SCRIPT = fileURLToPath(new URL('../bin/index.mjs', import.meta.url));
const MARKER = '<!-- Generated by bin/index.mjs from artifact frontmatter. Do not edit; changes are overwritten. -->';

// A project directory whose name contains a space, like the router tests use.
const mkProj = (cfg) => {
  const d = mkdtempSync(join(tmpdir(), 'sdd idx '));
  if (cfg !== undefined) writeFileSync(join(d, 'sdd.config.json'), typeof cfg === 'string' ? cfg : JSON.stringify(cfg));
  return d;
};
const put = (dir, rel, text) => {
  const f = join(dir, rel);
  mkdirSync(join(f, '..'), { recursive: true });
  writeFileSync(f, text);
  return f;
};
const fm = (o = {}) => {
  const f = { type: 'spec', title: 'T', description: 'D', status: 'draft', timestamp: '2026-10-08', ...o };
  const lines = Object.entries(f).filter(([, v]) => v !== undefined).map(([k, v]) => `${k}: ${v}`);
  return ['---', ...lines, '---', '', '# body', ''].join('\n');
};
const idx = (d) => readFileSync(join(d, 'docs/sdd/index.md'), 'utf8');

// ---------- grammar (AC-6) ----------
test('parseFrontmatter: a valid block yields its fields; LF, CRLF and BOM read alike', () => {
  const lf = fm({ title: 'Hello: world' });
  const a = I.parseFrontmatter(lf);
  assert.deepEqual(a.fields, { type: 'spec', title: 'Hello: world', description: 'D', status: 'draft', timestamp: '2026-10-08' });
  assert.deepEqual(I.parseFrontmatter(lf.replace(/\n/g, '\r\n')).fields, a.fields);
  assert.deepEqual(I.parseFrontmatter('﻿' + lf).fields, a.fields);
});

test('parseFrontmatter: blank lines and # comments are allowed; description and timestamp are optional', () => {
  const r = I.parseFrontmatter('---\n# note\n\ntype: plan\ntitle: P\nstatus: approved\n---\n');
  assert.deepEqual(r.fields, { type: 'plan', title: 'P', status: 'approved' });
});

test('parseFrontmatter: the closing delimiter may be on line 30 but not 31', () => {
  const pad = (n) => ['---', 'type: spec', 'title: T', 'status: draft', ...Array(n).fill('# c'), '---'].join('\n');
  assert.ok(I.parseFrontmatter(pad(25)).fields); // closing at line 30
  assert.equal(I.parseFrontmatter(pad(26)).reason, 'unterminated frontmatter'); // closing at line 31
});

test('parseFrontmatter: reasons', () => {
  const cases = [
    ['# Title\nno block', 'no frontmatter'],
    ['', 'no frontmatter'],
    ['---\ntype: spec\ntitle: T\nstatus: draft\n', 'unterminated frontmatter'],
    ['---\ntype: spec\nTitle: T\nstatus: draft\n---', 'malformed line 3'],
    ['---\ntype: spec\ntitle:T\nstatus: draft\n---', 'malformed line 3'],
    ['---\ntype: spec\ntitle: A\ntitle: B\nstatus: draft\n---', 'malformed line 4'],
    ['---\ntype: spec\ntitle:\nstatus: draft\n---', 'missing title'],
    ['---\ntitle: T\nstatus: draft\n---', 'missing type'],
    ['---\ntype: spec\nstatus: draft\n---', 'missing title'],
    ['---\ntype: spec\ntitle: T\n---', 'missing status'],
    ['---\ntype: note\ntitle: T\nstatus: draft\n---', 'unknown type note'],
  ];
  for (const [text, reason] of cases) assert.equal(I.parseFrontmatter(text).reason, reason, text);
});

test('parseFrontmatter: precedence — a malformed line wins over a missing key; unterminated wins over missing', () => {
  assert.equal(I.parseFrontmatter('---\ntype: spec\nbad line\n---').reason, 'malformed line 3');
  assert.equal(I.parseFrontmatter('---\ntype: spec\n').reason, 'unterminated frontmatter');
  assert.equal(I.parseFrontmatter('---\n---').reason, 'missing type');
});

// ---------- layout (AC-7) ----------
test('renderIndex: exact layout, None for empty sections, final newline', () => {
  assert.equal(
    I.renderIndex({ specs: [], plans: [], unindexed: [] }),
    `# SDD index\n\n${MARKER}\n\n## Specs\n\nNone\n\n## Plans\n\nNone\n\n## Unindexed\n\nNone\n`,
  );
  const text = I.renderIndex({
    specs: [{ rel: 'specs/a.md', title: 'A', status: 'approved', description: 'Does a.' }],
    plans: [{ rel: 'plans/a.md', title: 'A plan', status: 'draft' }],
    unindexed: [{ rel: 'specs/old.md', reason: 'no frontmatter' }],
  });
  assert.equal(
    text,
    `# SDD index\n\n${MARKER}\n\n## Specs\n\n- [A](specs/a.md) — approved — Does a.\n\n## Plans\n\n- [A plan](plans/a.md) — draft\n\n## Unindexed\n\n- specs/old.md — no frontmatter\n`,
  );
});

test('renderIndex: brackets in titles are escaped, spaces in links become %20, unindexed paths stay raw', () => {
  const t = I.renderIndex({
    specs: [{ rel: 'specs/my spec.md', title: 'Use [x] here', status: 's' }],
    plans: [],
    unindexed: [{ rel: 'specs/my old.md', reason: 'unreadable' }],
  });
  assert.ok(t.includes('- [Use \\[x\\] here](specs/my%20spec.md) — s\n'));
  assert.ok(t.includes('- specs/my old.md — unreadable\n'));
});

test('renderIndex: sorted by unencoded path in UTF-16 code-unit order, not locale order', () => {
  const t = I.renderIndex({
    specs: [
      { rel: 'specs/a.md', title: 'lower', status: 's' },
      { rel: 'specs/B.md', title: 'upper', status: 's' },
    ],
    plans: [],
    unindexed: [],
  });
  assert.ok(t.indexOf('[upper]') < t.indexOf('[lower]'));
});

// ---------- run (AC-5, AC-8 .. AC-11a) ----------
test('run: scans specs and plans, writes the Index, prints the summary, exit 0', () => {
  const d = mkProj();
  put(d, 'docs/sdd/specs/2026-01-a.md', fm({ title: 'Alpha' }));
  put(d, 'docs/sdd/plans/2026-01-a.md', fm({ type: 'plan', title: 'Alpha plan', status: 'approved' }));
  put(d, 'docs/sdd/specs/legacy.md', '# Legacy\n\n**Status:** approved\n');
  const r = I.run(d);
  assert.equal(r.code, 0);
  assert.equal(r.stdout, 'indexed 1 specs, 1 plans, 1 unindexed\n');
  const t = idx(d);
  assert.ok(t.includes('- [Alpha](specs/2026-01-a.md) — draft — D\n'));
  assert.ok(t.includes('- [Alpha plan](plans/2026-01-a.md) — approved — D\n'));
  assert.ok(t.includes('- specs/legacy.md — no frontmatter\n'));
});

test('run: only *.md files directly inside the directories are scanned', () => {
  const d = mkProj();
  put(d, 'docs/sdd/specs/a.md', fm());
  put(d, 'docs/sdd/specs/notes.txt', 'x');
  put(d, 'docs/sdd/specs/sub/b.md', fm());
  assert.equal(I.run(d).stdout, 'indexed 1 specs, 0 plans, 0 unindexed\n');
});

test('run: missing directories count as empty; parent directories of the Index are created', () => {
  const d = mkProj();
  const r = I.run(d);
  assert.equal(r.code, 0);
  assert.equal(r.stdout, 'indexed 0 specs, 0 plans, 0 unindexed\n');
  assert.equal(idx(d), I.renderIndex({ specs: [], plans: [], unindexed: [] }));
});

test('run: a second run is byte-identical and does not rewrite the file', () => {
  const d = mkProj();
  put(d, 'docs/sdd/specs/a.md', fm());
  I.run(d);
  const f = join(d, 'docs/sdd/index.md');
  const first = readFileSync(f);
  const old = new Date('2020-01-01T00:00:00Z');
  utimesSync(f, old, old);
  I.run(d);
  assert.deepEqual(readFileSync(f), first);
  assert.equal(statSync(f).mtime.getTime(), old.getTime());
});

test('run: the Index inside a scanned directory is skipped; no temp file is left behind', () => {
  const d = mkProj({ paths: { index: 'docs/sdd/specs/index.md' } });
  put(d, 'docs/sdd/specs/a.md', fm());
  I.run(d);
  const r = I.run(d);
  assert.equal(r.stdout, 'indexed 1 specs, 0 plans, 0 unindexed\n');
  assert.deepEqual(readdirSync(join(d, 'docs/sdd/specs')).sort(), ['a.md', 'index.md']);
});

test('run: specs and plans pointing at one directory scan it once', () => {
  const d = mkProj({ paths: { specs: 'docs/both', plans: 'docs/both' } });
  put(d, 'docs/both/a.md', fm());
  put(d, 'docs/both/b.md', fm({ type: 'plan', title: 'B' }));
  assert.equal(I.run(d).stdout, 'indexed 1 specs, 1 plans, 0 unindexed\n');
});

test('run: custom paths; links are relative to the Index directory', () => {
  const d = mkProj({ paths: { specs: 'a/s', plans: 'a/p', index: 'out/deep/idx.md' } });
  put(d, 'a/s/x.md', fm({ title: 'X' }));
  I.run(d);
  assert.ok(readFileSync(join(d, 'out/deep/idx.md'), 'utf8').includes('- [X](../../a/s/x.md) — draft — D\n'));
});

test('run: a foreign file at the Index path is not overwritten (exit 1); an empty one is', () => {
  const d = mkProj();
  const f = put(d, 'docs/sdd/index.md', '# My own notes\n');
  const r = I.run(d);
  assert.equal(r.code, 1);
  assert.ok(r.stderr.includes('docs/sdd/index.md'));
  assert.equal(readFileSync(f, 'utf8'), '# My own notes\n');
  writeFileSync(f, '  \n');
  assert.equal(I.run(d).code, 0);
  assert.ok(readFileSync(f, 'utf8').includes(MARKER));
  writeFileSync(f, '');
  assert.equal(I.run(d).code, 0);
});

test('run: a write failure exits 1 with one stderr line and leaves no temp file', () => {
  const d = mkProj();
  mkdirSync(join(d, 'docs/sdd/index.md'), { recursive: true }); // a directory where the file should go
  const r = I.run(d);
  assert.equal(r.code, 1);
  assert.equal(r.stderr.trim().split('\n').length, 1);
  assert.deepEqual(readdirSync(join(d, 'docs/sdd')), ['index.md']);
});

test('run: a specs path that is a file is treated as empty with a warning; exit stays 0', () => {
  const d = mkProj();
  put(d, 'docs/sdd/specs', 'not a directory');
  put(d, 'docs/sdd/plans/p.md', fm({ type: 'plan' }));
  const r = I.run(d);
  assert.equal(r.code, 0);
  assert.ok(r.stderr.includes('docs/sdd/specs'));
  assert.equal(r.stdout, 'indexed 0 specs, 1 plans, 0 unindexed\n');
});

test('run: an unreadable file is listed as unindexed (skipped on win32)', { skip: process.platform === 'win32' }, () => {
  const d = mkProj();
  const f = put(d, 'docs/sdd/specs/a.md', fm());
  chmodSync(f, 0);
  let readable = true;
  try { readFileSync(f); } catch { readable = false; } // running as root still reads it
  const r = I.run(d);
  assert.equal(r.code, 0);
  if (!readable) assert.ok(idx(d).includes('- specs/a.md — unreadable\n'));
});

test('run: an invalid config prints the one-line error and uses the default paths', () => {
  const d = mkProj('{ not json');
  put(d, 'docs/sdd/specs/a.md', fm());
  const r = I.run(d);
  assert.equal(r.code, 0);
  assert.ok(r.stderr.includes('sdd.config.json'));
  assert.equal(r.stdout, 'indexed 1 specs, 0 plans, 0 unindexed\n');
});

test('run: a bad paths.index is reported by loadConfig and defaults are used', () => {
  const d = mkProj({ paths: { index: 5 } });
  const r = I.run(d);
  assert.equal(r.code, 0);
  assert.ok(r.stderr.includes('paths.index'));
  assert.ok(existsSync(join(d, 'docs/sdd/index.md')));
});

test('CLI: runs from the project root (path with a space), prints the summary, exits 0', () => {
  const d = mkProj();
  put(d, 'docs/sdd/specs/a.md', fm());
  const r = spawnSync(process.execPath, [SCRIPT], { cwd: d, encoding: 'utf8' });
  assert.equal(r.status, 0);
  assert.equal(r.stdout, 'indexed 1 specs, 0 plans, 0 unindexed\n');
});

test('run: a split plan is listed by its manifest; the task folder beside it is not scanned', () => {
  const d = mkProj();
  put(d, 'docs/sdd/plans/p.md', fm({ type: 'plan', title: 'Split', layout: 'split' }));
  put(d, 'docs/sdd/plans/p/T1.md', '### T1 — One   [ ] pending\n');
  const r = I.run(d);
  assert.equal(r.code, 0, r.stderr);
  assert.equal(r.stdout, 'indexed 0 specs, 1 plans, 0 unindexed\n');
  assert.ok(idx(d).includes('- [Split](plans/p.md) — draft — D'), idx(d));
  assert.ok(!idx(d).includes('T1'));
});
